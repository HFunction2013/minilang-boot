#!/bin/sh
# install.sh — build and install the minilang boot compiler + VM onto a
# standard user prefix (default ~/.local).
#
# Steps: fetch (or reuse a local checkout) -> compile on site -> lay down
# bin/ and lib/minilang -> add the prefix bin to PATH -> smoke-test the
# installed command.
#
# Layout under $PREFIX:
#   bin/minilang                     wrapper (sets MINILANG_DIR, execs the boot exe)
#   lib/minilang/bin/minilang        real boot binary
#   lib/minilang/runtime.c           C runtime for the native backend
#   lib/minilang/minilang.h          shared C headers
#   lib/minilang/minilang_runtime.h
#   lib/minilang/syslib/*.mil        bundled standard library
#
# Environment / flags:
#   MINILANG_PREFIX   install prefix (default $HOME/.local)
#   MINILANG_BOOT_REPO git URL to clone when no local checkout is used
#   MINILANG_BRANCH   branch/tag to clone (default experiment/asm-gen)
#   BOOT_SOURCE       reuse an existing boot source tree instead of cloning
#   KEEP_WORK=1       keep the temporary build tree for inspection
set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

PREFIX="${MINILANG_PREFIX:-$HOME/.local}"
REPO_URL="${MINILANG_BOOT_REPO:-https://github.com/HFunction2013/minilang-boot.git}"
BRANCH="${MINILANG_BRANCH:-experiment/asm-gen}"
BOOT_SOURCE="${BOOT_SOURCE:-}"

log()  { printf '\033[1;36m[install]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[install]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[install]\033[0m %s\n' "$*" >&2; exit 1; }

while [ $# -gt 0 ]; do
    case "$1" in
        --prefix) PREFIX="$2"; shift 2 ;;
        --source) BOOT_SOURCE="$2"; shift 2 ;;
        --repo)   REPO_URL="$2"; shift 2 ;;
        --branch) BRANCH="$2"; shift 2 ;;
        -h|--help)
            sed -n '2,24p' "$0"; exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
done

[ -n "$PREFIX" ] || die "empty prefix"

# ---- 1. Locate source: explicit override, local checkout, else clone ----
WORK=""
cleanup() { [ -n "$WORK" ] && [ -d "$WORK" ] && [ "${KEEP_WORK:-0}" != "1" ] && rm -rf "$WORK"; }
trap cleanup EXIT

if [ -z "$BOOT_SOURCE" ] && [ -f "$REPO_ROOT/main.c" ]; then
    BOOT_SOURCE="$REPO_ROOT"
    log "Using local checkout: $BOOT_SOURCE"
else
    WORK="$(mktemp -d)"
    log "Cloning $REPO_URL ($BRANCH) -> $WORK/boot"
    git clone --depth 1 --branch "$BRANCH" "$REPO_URL" "$WORK/boot"
    BOOT_SOURCE="$WORK/boot"
    ( cd "$BOOT_SOURCE" && git submodule update --init --recursive ) || \
        warn "syslib submodule did not initialize; system modules may be missing"
fi

[ -f "$BOOT_SOURCE/main.c" ] || die "boot source not found at $BOOT_SOURCE"

# ---- 2. Compile on site (Unix: make) ----
command -v make >/dev/null 2>&1 || die "make not found; install build-essential/xcode-tools"
command -v cc >/dev/null 2>&1 || command -v gcc >/dev/null 2>&1 || die "C compiler (cc/gcc) not found"

log "Building boot compiler in $BOOT_SOURCE"
( cd "$BOOT_SOURCE" && make clean >/dev/null 2>&1 || true && make )

BOOT_BIN="$BOOT_SOURCE/minilang"
[ -x "$BOOT_BIN" ] || die "build failed: $BOOT_BIN not produced"

# ---- 3. Lay down the install tree ----
LIB="$PREFIX/lib/minilang"
BINDIR="$LIB/bin"
log "Installing to $PREFIX"
mkdir -p "$BINDIR" "$LIB/syslib" "$PREFIX/bin"

cp "$BOOT_BIN" "$BINDIR/minilang"
chmod +x "$BINDIR/minilang"

for f in runtime.c minilang.h minilang_runtime.h; do
    [ -f "$BOOT_SOURCE/$f" ] && cp "$BOOT_SOURCE/$f" "$LIB/"
done
if [ -d "$BOOT_SOURCE/syslib" ]; then
    for f in "$BOOT_SOURCE"/syslib/*.mil; do
        [ -f "$f" ] && cp "$f" "$LIB/syslib/"
    done
fi

# ---- 4. Wrapper on PATH: anchor MINILANG_DIR to the installed lib dir ----
WRAPPER="$PREFIX/bin/minilang"
cat > "$WRAPPER" <<EOF
#!/bin/sh
# Generated by minilang-boot/scripts/install.sh.
: "\${MINILANG_DIR:=$LIB}"
export MINILANG_DIR
exec "$BINDIR/minilang" "\$@"
EOF
chmod +x "$WRAPPER"

# ---- 5. Add $PREFIX/bin to the shell PATH (idempotent) ----
PATH_LINE='export PATH="'"$PREFIX"'/bin:$PATH"'
PROFILES="$HOME/.bashrc $HOME/.bash_profile $HOME/.zshrc $HOME/.profile"
for rc in $PROFILES; do
    [ -f "$rc" ] || continue
    if ! grep -qF "$PATH_LINE" "$rc" 2>/dev/null; then
        log "Adding PATH to $rc"
        printf '\n# minilang install\n%s\n' "$PATH_LINE" >> "$rc"
    fi
done
case ":$PATH:" in
    *":$PREFIX/bin:"*) ;;
    *) warn "$PREFIX/bin is not on PATH in this shell; reopen your terminal or run: export PATH=\"$PREFIX/bin:\$PATH\"" ;;
esac

# ---- 6. Smoke test the installed command ----
TMPTEST="$(mktemp -d)"
cat > "$TMPTEST/hello.mil" <<'EOF'
func main() {
    println "minilang install OK";
    return 0;
}
EOF
log "Smoke test: installed minilang runs a program"
( cd "$TMPTEST" && "$WRAPPER" run hello.mil )

rm -rf "$TMPTEST"
log "Done. Run 'minilang' from a fresh shell (or '$WRAPPER')."
